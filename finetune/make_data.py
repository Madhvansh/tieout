"""Write the training set for the local planner: (question, plan) pairs sampled from the graph's own vocabulary.

A plan is sampled first (so it is valid by construction), then put into words
with a frame, a way of naming the company, a way of naming the concept and a
way of naming the period. Validation uses frames and phrasings that never
appear in training, so the validation score says something about wording the
model has not seen. The real test is the hand-written benchmark, whose
questions were written by reading the PDFs, not from these frames.

Usage: python finetune/make_data.py [--train 12000] [--val 600] [--seed 5]
Writes finetune/data/train.jsonl, finetune/data/val.jsonl, finetune/system_prompt.txt
"""
